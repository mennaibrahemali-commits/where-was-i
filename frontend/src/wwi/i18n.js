export const DICTS = { ar, en };

export function makeT(lang) {
  const dict = DICTS[lang] || ar;
  return function t(key, vars) {
    let s = dict[key] ?? ar[key] ?? key;
    if (Array.isArray(s)) s = s[Math.floor(Math.random() * s.length)];
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', v);
    }
    return s;
  };
}

// Stable variant per day (for greetings that shouldn't flicker on re-render).
export function pickDaily(lang, key, seed = new Date().toDateString()) {
  const dict = DICTS[lang] || ar;
  const arr = dict[key];
  if (!Array.isArray(arr)) return arr;
  let h = 0;
  for (const c of seed + key) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return arr[h % arr.length];
}

export function formatNumber(n, lang) {
  return Number(n).toLocaleString(lang === 'ar' ? 'ar-EG' : 'en');
}
